package shape;

/* =========================================
 * ObjectType - 基本物件的型別 (取代魔術字串 "Rect"/"Oval")
 * =========================================
 * 用 enum 取得型別安全：打錯字編譯期就會報錯，IDE 也能自動完成。
 */
public enum ObjectType {
    RECT,   // 矩形
    OVAL,   // 橢圓
    CLASS   // UML 類別：分成「名稱 / 屬性 / 方法」三格的矩形
}
